#!/usr/bin/env node
/**
 * Cocoya image tooling.
 *
 *   npm run images:blur
 *     Regenerates src/content/image-blur.ts — tiny blurred previews used while
 *     photos load. Run after adding/replacing anything in /public/images.
 *
 *   npm run images:process -- <input-file> <output-path-under-public/images>
 *     e.g. npm run images:process -- ~/Downloads/IMG_2041.jpg menu/cappuccino.jpg
 *     Resizes, applies the Cocoya colour grade (warm highlights, gentle
 *     contrast, soft vignette) so new photos match the rest of the site, saves
 *     an optimised JPEG and refreshes the blur map.
 *     Add --no-grade to keep the original colours.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imagesDir = path.join(root, "public", "images");
const blurFile = path.join(root, "src", "content", "image-blur.ts");

const MAX_WIDTH = { brand: 2400, story: 1600, gallery: 1600, menu: 1200 };
const WARM = [
  [1.05, 0.03, 0.0],
  [0.01, 1.0, 0.0],
  [0.0, 0.03, 0.92],
];

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : /\.(jpe?g|png|webp|avif)$/i.test(e.name) ? [p] : [];
  });
}

async function generateBlur() {
  const files = walk(imagesDir).sort();
  const entries = [];
  for (const file of files) {
    const buf = await sharp(file).resize(12, 12, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
    const key = "/" + path.relative(path.join(root, "public"), file).split(path.sep).join("/");
    entries.push(`  ${JSON.stringify(key)}: "data:image/webp;base64,${buf.toString("base64")}",`);
  }
  const out = `// AUTO-GENERATED by \`npm run images:blur\` — do not edit by hand.\n// Tiny blurred previews shown while full-resolution photos load.\n\nexport const imageBlur: Record<string, string> = {\n${entries.join("\n")}\n};\n\nexport function blurFor(src: string): string | undefined {\n  return imageBlur[src];\n}\n`;
  fs.writeFileSync(blurFile, out);
  console.log(`✓ Blur placeholders generated for ${entries.length} images → src/content/image-blur.ts`);
}

function vignette(w, h, strength) {
  return Buffer.from(
    `<svg width="${w}" height="${h}" xmlns="http://www.w3.org/2000/svg"><defs><radialGradient id="g" cx="50%" cy="50%" r="75%"><stop offset="55%" stop-color="#000" stop-opacity="0"/><stop offset="100%" stop-color="#140b05" stop-opacity="${strength}"/></radialGradient></defs><rect width="100%" height="100%" fill="url(#g)"/></svg>`,
  );
}

async function processImage(input, output, { grade }) {
  if (!input || !output) {
    console.error("Usage: npm run images:process -- <input-file> <output-path-under-public/images> [--no-grade]");
    process.exit(1);
  }
  const outPath = path.join(imagesDir, output);
  const folder = output.split(/[\\/]/)[0];
  const maxWidth = MAX_WIDTH[folder] ?? 1600;
  const meta = await sharp(input).metadata();
  let pipeline = sharp(input).rotate().resize({ width: Math.min(maxWidth, meta.width ?? maxWidth), withoutEnlargement: true });
  let buf = await pipeline.toBuffer();
  if (grade) {
    const { width, height } = await sharp(buf).metadata();
    const editorial = folder !== "menu";
    buf = await sharp(buf)
      .recomb(WARM)
      .modulate({ saturation: 1.07, brightness: editorial ? 0.98 : 1.01 })
      .linear(1.07, -9)
      .gamma(2.2, 2.1)
      .toBuffer();
    buf = await sharp(buf)
      .composite([{ input: vignette(width, height, editorial ? 0.42 : 0.16), blend: "multiply" }])
      .toBuffer();
  }
  const out = await sharp(buf).sharpen({ sigma: 0.6 }).jpeg({ quality: 80, mozjpeg: true, progressive: true }).toBuffer();
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, out);
  console.log(`✓ Saved /images/${output.split(path.sep).join("/")} (${Math.round(out.length / 1024)} KB)`);
  await generateBlur();
}

const [command, ...rest] = process.argv.slice(2);
const flags = new Set(rest.filter((a) => a.startsWith("--")));
const args = rest.filter((a) => !a.startsWith("--"));

if (command === "blur") await generateBlur();
else if (command === "process") await processImage(args[0], args[1], { grade: !flags.has("--no-grade") });
else {
  console.log("Commands: blur | process <input> <output>");
  process.exit(1);
}
