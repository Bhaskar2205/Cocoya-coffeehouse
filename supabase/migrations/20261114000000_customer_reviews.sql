-- =============================================================================
--  Cocoya Coffee House — guest feedback schema
-- =============================================================================
--  Security model
--  • Guests never talk to the database directly. The Next.js API route
--    validates every submission and inserts it with the server-only secret key.
--  • Row Level Security is ON. The anon role has NO access to feedback at all.
--  • Only authenticated users listed in public.admin_users can read feedback
--    (including phone numbers) and they may update ONLY review_status and
--    is_featured (column-level grants).
--  • Feedback is never published automatically. It appears on the website only
--    if the guest opted in (display_consent) AND an admin featured it.
-- =============================================================================

create extension if not exists pgcrypto;

-- ── Types ────────────────────────────────────────────────────────────────────
do $$ begin
  create type public.review_status as enum ('new', 'reviewed', 'resolved');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.recommendation_choice as enum ('yes', 'maybe', 'no');
exception when duplicate_object then null; end $$;

-- ── Feedback table ───────────────────────────────────────────────────────────
create table if not exists public.customer_reviews (
  id                    uuid primary key default gen_random_uuid(),
  customer_name         text not null
                        check (char_length(customer_name) between 2 and 80),
  mobile_number         text not null
                        check (mobile_number ~ '^[0-9]{6,14}$'),
  country_code          text not null default '+91'
                        check (country_code ~ '^\+[0-9]{1,4}$'),
  rating                smallint not null
                        check (rating between 1 and 5),
  experience_categories text[] not null default '{}'
                        check (experience_categories <@ array['coffee','food','ambience','service','staff','overall']::text[]),
  additional_feedback   text
                        check (additional_feedback is null or char_length(additional_feedback) <= 1000),
  recommendation        public.recommendation_choice not null,
  privacy_consent       boolean not null
                        check (privacy_consent = true),
  display_consent       boolean not null default false,
  is_featured           boolean not null default false,
  review_status         public.review_status not null default 'new',
  -- Idempotency key generated by the form: a double-click can never create two rows.
  submission_key        uuid not null unique,
  -- Keyed hash of the submitter's IP (never the raw IP) — used for rate limiting.
  ip_hash               text,
  user_agent            text check (user_agent is null or char_length(user_agent) <= 400),
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  constraint featured_requires_display_consent check (not is_featured or display_consent),
  -- Indian numbers must be 10 digits starting 6–9.
  constraint indian_mobile_format check (country_code <> '+91' or mobile_number ~ '^[6-9][0-9]{9}$')
);

comment on table public.customer_reviews is 'Guest feedback submitted through the Cocoya website. Contains personal data (phone numbers) — admin access only.';

create index if not exists customer_reviews_created_at_idx on public.customer_reviews (created_at desc);
create index if not exists customer_reviews_rating_idx on public.customer_reviews (rating);
create index if not exists customer_reviews_status_idx on public.customer_reviews (review_status);
create index if not exists customer_reviews_ip_recent_idx on public.customer_reviews (ip_hash, created_at desc);
create index if not exists customer_reviews_mobile_recent_idx on public.customer_reviews (mobile_number, created_at desc);
create index if not exists customer_reviews_featured_idx on public.customer_reviews (created_at desc) where is_featured;

-- Keep updated_at fresh
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists customer_reviews_touch_updated_at on public.customer_reviews;
create trigger customer_reviews_touch_updated_at
  before update on public.customer_reviews
  for each row execute function public.touch_updated_at();

-- ── Administrators ───────────────────────────────────────────────────────────
-- Add an admin:  insert into public.admin_users (user_id) values ('<auth user uuid>');
create table if not exists public.admin_users (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

drop policy if exists "Admins can read their own membership" on public.admin_users;
create policy "Admins can read their own membership"
  on public.admin_users for select
  to authenticated
  using (user_id = (select auth.uid()));

revoke all on public.admin_users from anon, authenticated;
grant select on public.admin_users to authenticated;

-- SECURITY DEFINER so policies can check membership without recursive RLS.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users where user_id = (select auth.uid())
  );
$$;

revoke execute on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

-- ── Row Level Security for feedback ─────────────────────────────────────────
alter table public.customer_reviews enable row level security;

-- Lock everything down first, then grant the minimum.
revoke all on public.customer_reviews from anon, authenticated;
grant select on public.customer_reviews to authenticated;
grant update (review_status, is_featured) on public.customer_reviews to authenticated;

drop policy if exists "Admins can read feedback" on public.customer_reviews;
create policy "Admins can read feedback"
  on public.customer_reviews for select
  to authenticated
  using ((select public.is_admin()));

drop policy if exists "Admins can update feedback status" on public.customer_reviews;
create policy "Admins can update feedback status"
  on public.customer_reviews for update
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

-- No INSERT / DELETE policies: guests insert only via the server (secret key),
-- and feedback cannot be deleted from the dashboard.

-- ── Dashboard statistics (runs with the caller's permissions → admins only) ─
create or replace function public.review_stats()
returns table (
  total_reviews   bigint,
  average_rating  numeric,
  five_star       bigint,
  new_reviews     bigint,
  would_recommend bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    count(*)                                              as total_reviews,
    coalesce(round(avg(rating)::numeric, 2), 0)           as average_rating,
    count(*) filter (where rating = 5)                    as five_star,
    count(*) filter (where review_status = 'new')         as new_reviews,
    count(*) filter (where recommendation = 'yes')        as would_recommend
  from public.customer_reviews;
$$;

revoke execute on function public.review_stats() from public, anon;
grant execute on function public.review_stats() to authenticated;
